import { getGateway } from '../lib/gateway/singleton';
const gw = getGateway();
await gw.init();
const drv = await gw.getOrConnectDriver('fuckip-us');
console.log('driver alive', drv.isAlive());
const ch = await drv.spawnPiRpc({ cwd: '/root' });
const seen: any[] = [];
ch.onMessage((m) => { seen.push(m); });
ch.onError((e) => console.log('ERR', e.message.slice(0,300)));
ch.onClose((c) => console.log('CLOSE', c));
await new Promise(r => setTimeout(r, 3000));
ch.send({ type: 'get_state' });
await new Promise(r => setTimeout(r, 3000));
ch.send({ type: 'prompt', message: 'say hi in 3 words' });
await new Promise(r => setTimeout(r, 15000));
console.log('--- message types ---');
for (const m of seen) console.log(JSON.stringify(m).slice(0, 300));
ch.close();
process.exit(0);

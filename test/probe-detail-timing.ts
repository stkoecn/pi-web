const { listRemoteSessions, findRemoteSessionFile, readRemoteSessionContent, openRemoteSessionManager } = await import("../lib/remote-session-store");
const { buildSessionContext } = await import("../lib/session-reader");
const dev = "fuckip-us";
let t = Date.now();
const list = await listRemoteSessions(dev, { force: true });
console.log("list", Date.now() - t, "ms", list.length);
t = Date.now();
const f = await findRemoteSessionFile(dev, list[0].id);
console.log("find", Date.now() - t, "ms", f?.path, f?.size);
t = Date.now();
const c = await readRemoteSessionContent(dev, f!, { force: true });
console.log("sftp-read", Date.now() - t, "ms", c.length, "bytes");
t = Date.now();
const m = await openRemoteSessionManager(dev, list[0].id);
console.log("open-mgr", Date.now() - t, "ms", m?.sm.getEntries().length, "entries");
t = Date.now();
const ctx = buildSessionContext(m!.sm.getEntries(), m!.sm.getLeafId(), { deferThinking: true, deferToolResultImages: true, tail: 50, sessionId: list[0].id });
console.log("context", Date.now() - t, "ms", ctx.messages.length, "msgs");
process.exit(0);
